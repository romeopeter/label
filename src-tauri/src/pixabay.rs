//! Free image search, through Pixabay.
//!
//! This lives in Rust so the API key never reaches the webview. Errors are
//! deliberately plain values: an HTTP client's own errors include the request
//! URL, and this request's URL contains the key.

use std::{
    collections::HashMap,
    fs, io,
    path::{Path, PathBuf},
    sync::Mutex,
    time::{Duration, SystemTime, UNIX_EPOCH},
};

use reqwest::{Client, StatusCode, Url, redirect::Policy};
use serde::{Deserialize, Serialize};
use tauri::{State, ipc::Response};

const API_KEY: Option<&str> = option_env!("LAYER_PIXABAY_KEY");
const SEARCH_URL: &str = "https://pixabay.com/api/";

/// Pixabay's limit.
const MAX_QUERY_CHARS: usize = 100;
const PER_PAGE: u32 = 30;
const SEARCH_TIMEOUT: Duration = Duration::from_secs(15);
const DOWNLOAD_TIMEOUT: Duration = Duration::from_secs(60);

/// Pixabay's API terms require caching requests for 24 hours.
const CACHE_LIFETIME: Duration = Duration::from_secs(24 * 60 * 60);
const CACHE_ENTRIES: usize = 128;

/// Largest images here are 1280 px, so this only stops a surprise response.
const MAX_IMAGE_BYTES: usize = 50 * 1024 * 1024;

const IMAGE_HOSTS: [&str; 2] = ["pixabay.com", "cdn.pixabay.com"];

/// Pixabay serves at most 500 results for one search, so picks come from these pages.
pub const PICK_PAGES: u32 = 500 / PER_PAGE;

/// Real photographs only. `image_type=photo` already leaves out illustrations and
/// vectors; these tags catch what still gets through, such as AI pictures and
/// photos of artwork.
const NOT_PHOTOGRAPHY: [&str; 14] = [
    "ai generated",
    "ai-generated",
    "generated by ai",
    "generative ai",
    "illustration",
    "drawing",
    "painting",
    "vector",
    "clipart",
    "clip art",
    "icon",
    "cartoon",
    "3d render",
    "digital art",
];

#[derive(Debug, thiserror::Error)]
enum PixabayError {
    #[error("Image search isn't set up in this version of Layer.")]
    NoKey,
    #[error("Too many searches right now. Try again in a minute.")]
    RateLimited,
    #[error("Layer couldn't reach Pixabay. Check your connection and try again.")]
    Unreachable,
    #[error("Pixabay sent something Layer can't use. Try again in a moment.")]
    BadResponse,
    #[error("Layer can't download an image from there.")]
    UntrustedUrl,
    #[error("This image is too large to add.")]
    TooLarge,
}

#[derive(Deserialize)]
struct ApiPage {
    #[serde(rename = "totalHits")]
    total_hits: u64,
    hits: Vec<ApiHit>,
}

#[derive(Deserialize)]
struct ApiHit {
    id: u64,
    #[serde(rename = "type", default)]
    kind: String,
    tags: String,
    #[serde(rename = "previewURL")]
    preview_url: String,
    #[serde(rename = "largeImageURL")]
    large_image_url: String,
}

#[derive(Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct StockImage {
    id: u64,
    tags: String,
    preview_url: String,
    large_image_url: String,
}

#[derive(Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct StockPage {
    images: Vec<StockImage>,
    has_more: bool,
}

impl StockPage {
    fn from_api(api: ApiPage, page: u32) -> Self {
        Self {
            has_more: u64::from(page) * u64::from(PER_PAGE) < api.total_hits,
            images: api
                .hits
                .into_iter()
                .filter(is_photograph)
                .map(|hit| StockImage {
                    id: hit.id,
                    tags: hit.tags,
                    preview_url: hit.preview_url,
                    large_image_url: hit.large_image_url,
                })
                .collect(),
        }
    }
}

fn is_photograph(hit: &ApiHit) -> bool {
    let tags = hit.tags.to_lowercase();
    hit.kind == "photo" && !NOT_PHOTOGRAPHY.iter().any(|word| tags.contains(word))
}

type CacheKey = (String, u32);

#[derive(Clone, Serialize, Deserialize)]
struct CacheEntry {
    query: String,
    page: u32,
    stored_at: u64,
    result: StockPage,
}

/// Saved to a file so it survives a restart, since SQLite is still deferred. It
/// holds searches and Pixabay's URLs, never the key.
pub struct SearchCache {
    entries: Mutex<HashMap<CacheKey, CacheEntry>>,
    path: Option<PathBuf>,
}

fn now_secs() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |elapsed| elapsed.as_secs())
}

/// False for a time in the future too, so a changed clock can't keep it forever.
fn is_fresh(stored_at: u64, now: u64) -> bool {
    now.checked_sub(stored_at)
        .is_some_and(|age| age < CACHE_LIFETIME.as_secs())
}

impl SearchCache {
    /// A missing or damaged file just means starting with an empty cache.
    pub fn load(path: Option<PathBuf>) -> Self {
        let now = now_secs();
        let saved: Vec<CacheEntry> = path
            .as_ref()
            .and_then(|path| fs::read(path).ok())
            .and_then(|bytes| serde_json::from_slice(&bytes).ok())
            .unwrap_or_default();
        let entries = saved
            .into_iter()
            .filter(|entry| is_fresh(entry.stored_at, now))
            .map(|entry| ((entry.query.clone(), entry.page), entry))
            .collect();
        Self {
            entries: Mutex::new(entries),
            path,
        }
    }

    fn get(&self, key: &CacheKey, now: u64) -> Option<StockPage> {
        let entries = self.entries.lock().unwrap_or_else(|e| e.into_inner());
        let entry = entries.get(key)?;
        is_fresh(entry.stored_at, now).then(|| entry.result.clone())
    }

    /// Returns what to save, so the disk write can happen away from the lock.
    fn put(&self, key: CacheKey, result: StockPage, now: u64) -> Vec<CacheEntry> {
        let mut entries = self.entries.lock().unwrap_or_else(|e| e.into_inner());
        entries.retain(|_, entry| is_fresh(entry.stored_at, now));
        if entries.len() >= CACHE_ENTRIES
            && let Some(oldest) = entries
                .iter()
                .min_by_key(|(_, entry)| entry.stored_at)
                .map(|(key, _)| key.clone())
        {
            entries.remove(&oldest);
        }
        let entry = CacheEntry {
            query: key.0.clone(),
            page: key.1,
            stored_at: now,
            result,
        };
        entries.insert(key, entry);
        entries.values().cloned().collect()
    }
}

/// All or nothing, so a crash mid-write can't leave half a file behind.
fn save_entries(path: &Path, entries: &[CacheEntry]) -> io::Result<()> {
    let directory = path.parent().ok_or(io::ErrorKind::InvalidInput)?;
    fs::create_dir_all(directory)?;
    let mut file = tempfile::NamedTempFile::new_in(directory)?;
    serde_json::to_writer(&mut file, entries)?;
    file.persist(path)?;
    Ok(())
}

/// The form a search is cached under, and sent as.
fn normalize_query(query: &str) -> String {
    query
        .trim()
        .chars()
        .take(MAX_QUERY_CHARS)
        .collect::<String>()
        .to_lowercase()
}

/// The UI names what to download, so only Pixabay's own image hosts are allowed.
fn image_url(raw: &str) -> Result<Url, PixabayError> {
    let url = Url::parse(raw).map_err(|_| PixabayError::UntrustedUrl)?;
    let trusted = url.scheme() == "https"
        && url.port().is_none()
        && url.username().is_empty()
        && url.password().is_none()
        && url
            .host_str()
            .is_some_and(|host| IMAGE_HOSTS.contains(&host));
    if trusted {
        Ok(url)
    } else {
        Err(PixabayError::UntrustedUrl)
    }
}

/// No redirects: one could leave the hosts `image_url` allows, or carry the key.
fn client(timeout: Duration) -> Result<Client, PixabayError> {
    Client::builder()
        .timeout(timeout)
        .redirect(Policy::none())
        .build()
        .map_err(|_| PixabayError::Unreachable)
}

fn check_status(status: StatusCode) -> Result<(), PixabayError> {
    match status {
        StatusCode::TOO_MANY_REQUESTS => Err(PixabayError::RateLimited),
        status if status.is_success() => Ok(()),
        _ => Err(PixabayError::BadResponse),
    }
}

/// With no words, Pixabay's editors' choice: photos to pick from before searching.
async fn fetch_page(query: &str, page: u32) -> Result<StockPage, PixabayError> {
    let key = API_KEY.ok_or(PixabayError::NoKey)?;
    let mut params = vec![
        ("key", key.to_owned()),
        ("q", query.to_owned()),
        ("image_type", "photo".to_owned()),
        ("safesearch", "true".to_owned()),
        ("page", page.to_string()),
        ("per_page", PER_PAGE.to_string()),
    ];
    if query.is_empty() {
        params.push(("editors_choice", "true".to_owned()));
        params.push(("order", "popular".to_owned()));
    }
    let response = client(SEARCH_TIMEOUT)?
        .get(SEARCH_URL)
        .query(&params)
        .send()
        .await
        .map_err(|_| PixabayError::Unreachable)?;
    check_status(response.status())?;

    let body = response
        .bytes()
        .await
        .map_err(|_| PixabayError::Unreachable)?;
    let api: ApiPage = serde_json::from_slice(&body).map_err(|_| PixabayError::BadResponse)?;
    Ok(StockPage::from_api(api, page))
}

async fn fetch_image(url: Url) -> Result<Vec<u8>, PixabayError> {
    let mut response = client(DOWNLOAD_TIMEOUT)?
        .get(url)
        .send()
        .await
        .map_err(|_| PixabayError::Unreachable)?;
    check_status(response.status())?;

    let is_image = response
        .headers()
        .get(reqwest::header::CONTENT_TYPE)
        .and_then(|value| value.to_str().ok())
        .is_some_and(|value| value.starts_with("image/"));
    if !is_image {
        return Err(PixabayError::BadResponse);
    }

    let mut bytes = Vec::new();
    while let Some(chunk) = response
        .chunk()
        .await
        .map_err(|_| PixabayError::Unreachable)?
    {
        if bytes.len() + chunk.len() > MAX_IMAGE_BYTES {
            return Err(PixabayError::TooLarge);
        }
        bytes.extend_from_slice(&chunk);
    }
    Ok(bytes)
}

#[tauri::command]
pub async fn search_images(
    cache: State<'_, SearchCache>,
    query: String,
    page: u32,
) -> Result<StockPage, String> {
    let query = normalize_query(&query);
    // Picks stop where Pixabay's results do.
    let page = if query.is_empty() {
        page.clamp(1, PICK_PAGES)
    } else {
        page.max(1)
    };

    let key = (query, page);
    if let Some(cached) = cache.get(&key, now_secs()) {
        return Ok(cached);
    }
    let mut result = fetch_page(&key.0, page)
        .await
        .map_err(|error| error.to_string())?;
    if key.0.is_empty() && page >= PICK_PAGES {
        result.has_more = false;
    }
    let entries = cache.put(key, result.clone(), now_secs());
    if let Some(path) = cache.path.clone() {
        // A cache that can't be saved only costs a repeat search next launch.
        let _ = tauri::async_runtime::spawn_blocking(move || save_entries(&path, &entries)).await;
    }
    Ok(result)
}

/// Downloaded rather than linked: Pixabay's terms don't allow keeping its URLs in
/// a project. Raw bytes, because a JSON-encoded image would be slow over IPC.
#[tauri::command]
pub async fn download_image(url: String) -> Result<Response, String> {
    let url = image_url(&url).map_err(|error| error.to_string())?;
    fetch_image(url)
        .await
        .map(Response::new)
        .map_err(|error| error.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn stock_page() -> StockPage {
        StockPage {
            images: Vec::new(),
            has_more: false,
        }
    }

    #[test]
    fn image_url_allows_only_pixabay_over_https() {
        for good in [
            "https://pixabay.com/get/abc_1280.jpg",
            "https://cdn.pixabay.com/photo/a_150.jpg",
        ] {
            assert!(image_url(good).is_ok(), "{good}");
        }
        for bad in [
            "http://pixabay.com/get/a.jpg",
            "https://pixabay.com.evil.test/a.jpg",
            "https://evil.test/pixabay.com/a.jpg",
            "https://pixabay.com@evil.test/a.jpg",
            "https://user@pixabay.com/a.jpg",
            "https://pixabay.com:8443/a.jpg",
            "https://127.0.0.1/a.jpg",
            "file:///etc/passwd",
            "not a url",
        ] {
            assert!(image_url(bad).is_err(), "{bad}");
        }
    }

    #[test]
    fn normalize_query_trims_lowers_and_caps() {
        assert_eq!(normalize_query("  Yellow Flower "), "yellow flower");
        assert_eq!(normalize_query(&"a".repeat(150)).chars().count(), 100);
        assert_eq!(normalize_query(&"é".repeat(150)).chars().count(), 100);
    }

    #[test]
    fn parses_a_response_with_unknown_fields() {
        let body = r#"{"total":9,"totalHits":31,"newField":1,"hits":[{"id":7,"type":"photo","tags":"sky","previewURL":"https://cdn.pixabay.com/p_150.jpg","largeImageURL":"https://pixabay.com/get/l_1280.jpg","views":3}]}"#;
        let api: ApiPage = serde_json::from_str(body).expect("parses");

        let first = StockPage::from_api(api, 1);

        assert!(first.has_more);
        assert_eq!(first.images[0].id, 7);
        assert_eq!(
            first.images[0].large_image_url,
            "https://pixabay.com/get/l_1280.jpg"
        );
    }

    #[test]
    fn keeps_only_photographs() {
        let body = r#"{"totalHits":4,"hits":[
            {"id":1,"type":"photo","tags":"beach, sea","previewURL":"p","largeImageURL":"l"},
            {"id":2,"type":"illustration","tags":"beach","previewURL":"p","largeImageURL":"l"},
            {"id":3,"type":"photo","tags":"woman, AI Generated","previewURL":"p","largeImageURL":"l"},
            {"id":4,"type":"photo","tags":"oil painting, art","previewURL":"p","largeImageURL":"l"}
        ]}"#;
        let api: ApiPage = serde_json::from_str(body).expect("parses");

        let ids: Vec<u64> = StockPage::from_api(api, 1)
            .images
            .iter()
            .map(|image| image.id)
            .collect();

        assert_eq!(ids, [1]);
    }

    #[test]
    fn last_page_has_no_more() {
        let api = ApiPage {
            total_hits: 60,
            hits: Vec::new(),
        };
        assert!(!StockPage::from_api(api, 2).has_more);
    }

    #[test]
    fn status_maps_to_the_right_error() {
        assert!(check_status(StatusCode::OK).is_ok());
        assert!(matches!(
            check_status(StatusCode::TOO_MANY_REQUESTS),
            Err(PixabayError::RateLimited)
        ));
        assert!(matches!(
            check_status(StatusCode::BAD_REQUEST),
            Err(PixabayError::BadResponse)
        ));
    }

    const DAY: u64 = CACHE_LIFETIME.as_secs();
    const START: u64 = 1_000_000;

    #[test]
    fn cache_hits_within_a_day_and_misses_after() {
        let cache = SearchCache::load(None);
        let key = ("sky".to_owned(), 1);
        cache.put(key.clone(), stock_page(), START);

        assert!(cache.get(&key, START + DAY / 2).is_some());
        assert!(cache.get(&key, START + DAY).is_none());
    }

    #[test]
    fn cache_ignores_a_time_in_the_future() {
        let cache = SearchCache::load(None);
        let key = ("sky".to_owned(), 1);
        cache.put(key.clone(), stock_page(), START);

        assert!(cache.get(&key, START - 1).is_none());
    }

    #[test]
    fn cache_stays_bounded_and_drops_the_oldest() {
        let cache = SearchCache::load(None);
        for i in 0..=CACHE_ENTRIES {
            cache.put((format!("q{i}"), 1), stock_page(), START + i as u64);
        }
        let later = START + CACHE_ENTRIES as u64;

        assert!(cache.get(&("q0".to_owned(), 1), later).is_none());
        assert!(
            cache
                .get(&(format!("q{CACHE_ENTRIES}"), 1), later)
                .is_some()
        );
    }

    #[test]
    fn cache_survives_a_restart_and_drops_old_entries() {
        let directory = tempfile::tempdir().expect("create temp dir");
        let path = directory.path().join("nested").join("cache.json");
        let now = now_secs();
        let old = CacheEntry {
            query: "old".to_owned(),
            page: 1,
            stored_at: now - DAY - 1,
            result: stock_page(),
        };
        let fresh = CacheEntry {
            query: "fresh".to_owned(),
            page: 2,
            stored_at: now - 60,
            result: stock_page(),
        };
        save_entries(&path, &[old, fresh]).expect("saves");

        let reloaded = SearchCache::load(Some(path));

        assert!(reloaded.get(&("fresh".to_owned(), 2), now).is_some());
        let entries = reloaded.entries.lock().expect("not poisoned");
        assert_eq!(entries.len(), 1);
    }

    #[test]
    fn a_damaged_cache_file_starts_empty() {
        let directory = tempfile::tempdir().expect("create temp dir");
        let path = directory.path().join("cache.json");
        fs::write(&path, "not json").expect("write");

        let cache = SearchCache::load(Some(path));

        assert!(cache.entries.lock().expect("not poisoned").is_empty());
    }

    /// Calls the real service with the real key:
    /// `cargo test --all-features -- --ignored real_pixabay`
    #[tokio::test]
    #[ignore = "needs the network and an API key"]
    async fn real_pixabay_search_and_download() {
        let key = API_KEY.expect("key in the build");

        let found = fetch_page("yellow flower", 1).await.expect("search works");
        assert!(!found.images.is_empty());
        assert!(found.has_more);

        let json = serde_json::to_string(&found).expect("serializes");
        assert!(!json.contains(key), "the key must never reach the webview");

        let first = &found.images[0];
        println!("preview: {}", first.preview_url);
        let url = image_url(&first.large_image_url).expect("trusted host");
        let bytes = fetch_image(url).await.expect("download works");
        assert!(bytes.len() > 1000);
        image_url(&first.preview_url).expect("preview is a trusted host");
    }
}
